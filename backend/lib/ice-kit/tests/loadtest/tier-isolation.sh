#!/usr/bin/env bash
#
# TIER ISOLATION LOAD TEST — does free traffic stay inside its share and leave the paid reserve alone?
#
# Run it from a test machine near a TURN host, with short-lived credentials from the API host (no secret is
# needed or used here):
#
#   php lib/ice-kit/bin/probe.php --bootstrap=config/ice-kit.php --node=mum-paid   --tier=paid --emit-grant=/tmp/paid.json --ttl=900
#   php lib/ice-kit/bin/probe.php --bootstrap=config/ice-kit.php --node=mum-shared --tier=free --emit-grant=/tmp/free.json --ttl=900
#   scp the two files to the test machine (0600), then:
#
#   bash tier-isolation.sh --paid-host turn-mum.aicountly.com --paid-port 3478 \
#                          --free-host turn-mum-shared.aicountly.com --free-port 3479 \
#                          --paid-grant /tmp/paid.json --free-grant /tmp/free.json \
#                          --free-ceiling-kBps 25000 --paid-load-kBps 500 [--free-clients 12] [--seconds 60] [--tolerance 0.10]
#
# Three phases, each with real relayed traffic generated by coturn's own turnutils_uclient:
#   1. PAID ALONE      a steady paid flow  -> P0 (throughput) and its packet loss L0
#   2. FREE FLOOD      many free clients offering well over the free ceiling  -> F (what the relay lets through)
#   3. BOTH TOGETHER   the same paid flow while the flood runs  -> P1, L1
#
# PASS requires all of:
#   C1  F <= free ceiling x (1 + tolerance)          free is capped at its share
#   C2  P1 >= P0 x (1 - tolerance)                   paid lost nothing while free flooded
#   C3  L1 <= L0 + 0.5 percentage points            and no extra loss
#   C4  some free allocations were refused (486)     or the flood fitted under the cap (then say so)
#
# What it can and cannot show. On a node whose NIC is nowhere near saturated, C2/C3 pass trivially because nothing
# competes for the wire: size --free-clients and the flood so that free's OFFERED load exceeds the NIC headroom
# left by the paid reserve (the infrastructure team's shaper, infra/tier-split, is what must hold then). Run it
# once at low load for mechanics, once at saturation for the guarantee. Exit 0 only if every check that ran passed.
# Prints no credential.
set -uo pipefail

PAID_HOST=""; PAID_PORT=3478; FREE_HOST=""; FREE_PORT=3478; PAID_GRANT=""; FREE_GRANT=""
CEIL=0; PAID_LOAD=500; FREE_CLIENTS=8; SECS=60; TOL=0.10; MSG_LEN=1000
while [ $# -gt 0 ]; do
  case "$1" in
    --paid-host) PAID_HOST="$2"; shift 2 ;; --paid-port) PAID_PORT="$2"; shift 2 ;;
    --free-host) FREE_HOST="$2"; shift 2 ;; --free-port) FREE_PORT="$2"; shift 2 ;;
    --paid-grant) PAID_GRANT="$2"; shift 2 ;; --free-grant) FREE_GRANT="$2"; shift 2 ;;
    --free-ceiling-kBps) CEIL="$2"; shift 2 ;; --paid-load-kBps) PAID_LOAD="$2"; shift 2 ;;
    --free-clients) FREE_CLIENTS="$2"; shift 2 ;; --seconds) SECS="$2"; shift 2 ;; --tolerance) TOL="$2"; shift 2 ;;
    -h|--help) sed -n '2,36p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
for v in PAID_HOST FREE_HOST PAID_GRANT FREE_GRANT; do [ -n "${!v}" ] || { echo "--$(echo "$v" | tr 'A-Z_' 'a-z-') is required" >&2; exit 2; }; done
[ "$CEIL" -gt 0 ] || { echo "--free-ceiling-kBps is required (the shared instance's share of the NIC, in kbyte/s)" >&2; exit 2; }
command -v turnutils_uclient >/dev/null && command -v jq >/dev/null || { echo "needs turnutils_uclient (coturn-utils) and jq" >&2; exit 2; }

cred() { jq -r '[.iceServers[] | select(.username)][0] | "\(.username) \(.credential)"' "$1"; }
read -r PU PP < <(cred "$PAID_GRANT"); read -r FU FP < <(cred "$FREE_GRANT")
[ -n "$PU" ] && [ -n "$FU" ] || { echo "a grant file has no TURN credential" >&2; exit 2; }
case "$PU" in *:p.*) ;; *) echo "WARNING: the paid grant's username does not carry the p. tier marker" >&2 ;; esac
case "$FU" in *:f.*) ;; *) echo "WARNING: the free grant's username does not carry the f. tier marker" >&2 ;; esac

WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"; kill $(jobs -p) 2>/dev/null' EXIT
pass=0; fail=0
ok()  { printf '  \033[32mPASS\033[0m %s\n' "$1"; pass=$((pass + 1)); }
bad() { printf '  \033[31mFAIL\033[0m %s\n' "$1"; fail=$((fail + 1)); }

# uclient -z is the gap between messages in ms; messages of $MSG_LEN bytes at 1000/z per second per client.
msgs_for() { echo $(( SECS * 1000 / $1 )); }

run() { # label host port user clients z-ms msg-len -> writes $WORK/label.out
  timeout $((SECS + 60)) turnutils_uclient -y -m "$5" -n "$(msgs_for "$6")" -l "$7" -z "$6" -p "$3" -u "$4" -w "${CRED[$1]}" "$2" > "$WORK/$1.out" 2>&1
}
declare -A CRED=([paid_alone]="$PP" [paid_both]="$PP" [free]="$FP")

stat() { # file -> "bytes_per_sec lossPct refusals"
  local f="$1" r t l e
  r=$(grep -o 'tot_recv_bytes ~ [0-9]*' "$f" | tail -1 | awk '{print $3}'); t=$(grep -o 'Total transmit time is [0-9]*' "$f" | tail -1 | awk '{print $5}')
  l=$(grep -o 'Total lost packets [0-9]* ([0-9.]*%)' "$f" | tail -1 | grep -o '([0-9.]*' | tr -d '('); e=$(grep -c 'error 486' "$f")
  echo "$(( ${r:-0} / ( ${t:-0} > 0 ? t : 1 ) )) ${l:-0} ${e:-0}"
}

# Two paid clients at one message every 2 ms: together they offer (2 x len x 500) B/s = len kB/s, so len = PAID_LOAD (<= 1400).
PAID_LEN=$PAID_LOAD; [ "$PAID_LEN" -le 1400 ] || PAID_LEN=1400; [ "$PAID_LEN" -ge 50 ] || PAID_LEN=50
echo "tier isolation: paid ${PAID_HOST}:${PAID_PORT} (~${PAID_LEN} kB/s offered), free ${FREE_HOST}:${FREE_PORT} (${FREE_CLIENTS} clients, ceiling ${CEIL} kB/s), ${SECS}s per phase"

echo; echo "1. paid alone"
run paid_alone "$PAID_HOST" "$PAID_PORT" "$PU" 2 2 "$PAID_LEN"
read -r P0 L0 E0 < <(stat "$WORK/paid_alone.out"); echo "   paid: ${P0} B/s, loss ${L0}%, refused ${E0}"
[ "$E0" -eq 0 ] && [ "$P0" -gt 0 ] || { bad "the paid flow itself did not run (refused ${E0}, ${P0} B/s): fix the baseline first"; exit 1; }

echo; echo "2. free flood alone"
run free "$FREE_HOST" "$FREE_PORT" "$FU" "$FREE_CLIENTS" 2 1200
read -r F0 FL0 FE0 < <(stat "$WORK/free.out"); echo "   free: ${F0} B/s through, loss ${FL0}%, ${FE0} allocation(s) refused with 486"

echo; echo "3. both together"
run free "$FREE_HOST" "$FREE_PORT" "$FU" "$FREE_CLIENTS" 2 1200 &
sleep 5
run paid_both "$PAID_HOST" "$PAID_PORT" "$PU" 2 2 "$PAID_LEN"
wait
read -r P1 L1 E1 < <(stat "$WORK/paid_both.out"); read -r F1 FL1 FE1 < <(stat "$WORK/free.out")
echo "   paid: ${P1} B/s, loss ${L1}%, refused ${E1}   free: ${F1} B/s, loss ${FL1}%, refused ${FE1}"

echo; echo "checks (tolerance ${TOL})"
ceil_bytes=$(( CEIL * 1000 ))
awk -v f="$F0" -v f2="$F1" -v c="$ceil_bytes" -v t="$TOL" 'BEGIN { exit !((f <= c * (1 + t)) && (f2 <= c * (1 + t))) }' && ok "C1 free carried ${F0}/${F1} B/s, at or under its ceiling ${ceil_bytes} B/s (+${TOL})" || bad "C1 free carried ${F0}/${F1} B/s, OVER its ceiling ${ceil_bytes} B/s"
awk -v p0="$P0" -v p1="$P1" -v t="$TOL" 'BEGIN { exit !(p1 >= p0 * (1 - t)) }' && ok "C2 paid kept ${P1} of ${P0} B/s while free flooded" || bad "C2 paid fell from ${P0} to ${P1} B/s while free flooded"
awk -v l0="$L0" -v l1="$L1" 'BEGIN { exit !(l1 <= l0 + 0.5) }' && ok "C3 paid loss ${L1}% vs ${L0}% alone" || bad "C3 paid loss rose from ${L0}% to ${L1}%"
if [ "$FE0" -gt 0 ] || [ "$FE1" -gt 0 ]; then ok "C4 the free instance refused allocations beyond its capacity (486)"; else echo "  note: no free allocation was refused - the flood fitted under the instance's capacity; raise --free-clients to test the refusal path"; fi

echo; printf 'passed %d, failed %d\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
